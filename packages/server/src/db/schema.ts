// --- credentials + audit ----------------------------------------------------

/**
 * Minted, scoped API keys. `hash` carries a unique index because it is the
 * authentication hot path: every authenticated request is one lookup on it.
 */
export const apiKeys = pgTable(
  'api_keys',
  {
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organizations.id),
    name: text('name').notNull(),
    prefix: text('prefix').notNull(),
    /** sha256(token) as hex — see @driftwatch/sdk's api-keys.ts for why not a KDF. */
    hash: text('hash').notNull(),
    scopes: jsonb('scopes').$type<ApiKeyScope[]>().notNull(),
    /** Null/empty = fleet-wide. */
    agentIds: jsonb('agent_ids').$type<string[]>(),
    createdAt: bigint('created_at', { mode: 'number' }).notNull(),
    createdBy: text('created_by').notNull(),
    lastUsedAt: bigint('last_used_at', { mode: 'number' }),
    expiresAt: bigint('expires_at', { mode: 'number' }),
    /** Soft revoke: the row stays so the audit trail can still resolve id -> name. */
    revokedAt: bigint('revoked_at', { mode: 'number' }),
    revokedBy: text('revoked_by'),
  },
  (table) => [
    uniqueIndex('api_keys_hash_idx').on(table.hash),
    index('api_keys_org_idx').on(table.organizationId, table.createdAt),
  ],
);

/**
 * Every control-plane mutation worth attributing to a principal.
 *
 * `summary` MUST NOT contain secret plaintext: for a change that touches a
 * secret, name the FIELD that changed, never its before/after value.
 */
export const auditEvents = pgTable(
  'audit_events',
  {
    id: text('id').primaryKey(),
    seq: bigserial('seq', { mode: 'number' }).notNull(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organizations.id),
    at: bigint('at', { mode: 'number' }).notNull(),
    actor: text('actor').notNull(),
    actorLabel: text('actor_label').notNull(),
    action: text('action').$type<AuditAction>().notNull(),
    target: text('target'),
    agentId: text('agent_id'),
    summary: text('summary').notNull(),
  },
  (table) => [
    index('audit_events_at_idx').on(table.at),
    index('audit_events_agent_at_idx').on(table.agentId, table.at),
  ],
);

// --- coordination -----------------------------------------------------------

/**
 * Action-storm suppression, per (agent, key).
 *
 * In Redis this was SET NX PX; here it is an upsert whose WHERE clause makes the
 * check-and-set a single atomic statement — see PostgresStateStore. Expired rows
 * are overwritten in place rather than swept, so this table's size is bounded by
 * the number of distinct keys, not by time.
 */
export const cooldowns = pgTable(
  'cooldowns',
  {
    agentId: text('agent_id').notNull(),
    key: text('key').notNull(),
    expiresAt: bigint('expires_at', { mode: 'number' }).notNull(),
  },
  (table) => [primaryKey({ columns: [table.agentId, table.key] })],
);

/**
 * Best-effort leader election so only one process runs a drift cycle.
 *
 * Global, not per-agent: one leader runs the whole fleet's cycle per tick.
 * `holder` is diagnostic only — the lock is won by the atomic upsert, never by
 * comparing this value.
 */
export const leaderLocks = pgTable('leader_locks', {
  key: text('key').primaryKey(),
  expiresAt: bigint('expires_at', { mode: 'number' }).notNull(),
  holder: text('holder'),
});

// --- run summaries ----------------------------------------------------------

/**
 * One row per agent task run — the durable telemetry record that lets the
 * console show charts without Grafana, and lets `SqlMetricsSource` answer the
 * drift detector's window queries without Prometheus.
 *
 * Deliberately a SUMMARY, not raw spans. A span table would need partitioning
 * and a retention policy to survive real throughput, and would push the
 * deployment back toward ClickHouse/Tempo — exactly the multi-container
 * complexity this architecture is removing. One row per run instead of ~50
 * spans answers the operator questions ("what did this cost, what did it call,
 * did it fail") at a fraction of the write volume. Full distributed tracing
 * remains available to anyone exporting OTLP to a real trace backend, and
 * `traceId` is kept here so a run links straight to it.
 */
export const agentRuns = pgTable(
  'agent_runs',
  {
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organizations.id),
    agentId: text('agent_id').notNull(),
    startedAt: bigint('started_at', { mode: 'number' }).notNull(),
    endedAt: bigint('ended_at', { mode: 'number' }),
    durationMs: integer('duration_ms'),
    status: text('status').$type<'running' | 'completed' | 'failed' | 'stopped'>().notNull(),
    /** Why a run ended early: a guardrail breach, a tool denial, a model error. */
    stopReason: text('stop_reason'),
    errorMessage: text('error_message'),
    model: text('model'),
    steps: integer('steps'),
    promptTokens: integer('prompt_tokens'),
    completionTokens: integer('completion_tokens'),
    totalTokens: integer('total_tokens'),
    costUsd: doublePrecision('cost_usd'),
    /** Tool names called, in order, with per-call duration and outcome. */
    toolCalls: jsonb('tool_calls').$type<
      { tool: string; durationMs: number; ok: boolean; gated?: boolean }[]
    >(),
    /** Links to the full trace in whatever OTLP backend the deployment uses. */
    traceId: text('trace_id'),
  },
  (table) => [
    index('agent_runs_agent_started_idx').on(table.agentId, table.startedAt),
    index('agent_runs_started_idx').on(table.startedAt),
  ],
);

/**
 * Individual tool calls, extracted from runs so window queries can aggregate
 * latency and error rate per tool without unpacking every run's JSON.
 *
 * This is the table `SqlMetricsSource` reads to produce `WindowStats` — the
 * same shape `PrometheusMetricsSource` produces from PromQL, which is what
 * makes Prometheus optional rather than required.
 */
export const toolCallEvents = pgTable(
  'tool_call_events',
  {
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organizations.id),
    agentId: text('agent_id').notNull(),
    runId: text('run_id'),
    tool: text('tool').notNull(),
    at: bigint('at', { mode: 'number' }).notNull(),
    durationMs: doublePrecision('duration_ms').notNull(),
    ok: boolean('ok').notNull(),
    /** True when a Loop 3 policy gated this call (denied or held for approval). */
    gated: boolean('gated').notNull().default(false),
  },
  (table) => [
    index('tool_call_events_agent_at_idx').on(table.agentId, table.at),
    index('tool_call_events_agent_tool_at_idx').on(table.agentId, table.tool, table.at),
  ],
);

/**
 * Model-switch events, counted by the drift detector so a behavior change can be
 * attributed to an intentional switch rather than organic drift. Mirrors the
 * `agent.model.switches` counter that `PrometheusMetricsSource` queries.
 */
export const modelSwitches = pgTable(
  'model_switches',
  {
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organizations.id),
    agentId: text('agent_id').notNull(),
    at: bigint('at', { mode: 'number' }).notNull(),
    fromModel: text('from_model'),
    toModel: text('to_model'),
  },
  (table) => [index('model_switches_agent_at_idx').on(table.agentId, table.at)],
);
